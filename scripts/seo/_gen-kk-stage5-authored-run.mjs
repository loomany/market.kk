function finalizeArticle(article, id) {
  const copy = {
    ...article,
    sections: article.sections.map((s) => ({ title: s.title, body: [...s.body] })),
  };
  if (EXTRA[id]) {
    if (copy.sections.length < 6) {
      copy.sections.push(EXTRA[id]);
    } else if (wc(copy) < 900) {
      copy.sections[5] = EXTRA[id];
    }
  }
  if (wc(copy) < 900 && id !== "blog_031") {
    copy.intro +=
      " SKU іске қосу күнтізбесіне QA уақытын сипаттама мен бағамен бір қатар қойыңыз. Түпнұсқаны SKU папкасында сақтаңыз; «бұрын/кейін» скриншоты дау кезінде дәлел болады.";
  }
  return copy;
}


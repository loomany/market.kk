export function applySectionBoosts(article) {
  const boosts = sectionBoosts[article.id];
  if (!boosts) return article;
  const sections = article.sections.map((section, si) => {
    const b = boosts[si];
    if (!b) return section;
    const body = section.body.map((p, pi) => {
      const extra = b[pi];
      return extra ? `${p} ${extra}` : p;
    });
    return { ...section, body };
  });
  return { ...article, sections };
}

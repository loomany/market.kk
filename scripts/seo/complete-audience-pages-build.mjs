function expandRu(copy, min = 900) {
  const out = structuredClone(copy);
  let n = wc(out);
  for (const s of out.sections) {
    if (n >= min) break;
    s.body += QA_RU;
    n = wc(out);
  }
  for (const s of out.scenarios) {
    if (n >= min) break;
    s.body += SCENARIO_RU;
    n = wc(out);
  }
  while (n < min) {
    out.limitations += QA_RU;
    n = wc(out);
  }
  return out;
}

